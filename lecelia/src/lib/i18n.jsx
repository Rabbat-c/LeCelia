function makeT(lang) {
  return (key, vars) => {
    let str = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
    if (vars) Object.entries(vars).forEach(([k, v]) => { str = str.split(`{${k}}`).join(v); });
    return str;
  };
}
function makeTn(t) {
  return (key, n, vars) => t(n === 1 ? `${key}_one` : `${key}_other`, { n, ...vars });
}

